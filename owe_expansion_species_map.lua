function M.resolve(national, formId, unownLetter)
  local nat = tonumber(national)
  if not nat or nat < 1 or nat ~= math.floor(nat) then return nil end
  if formId and M.formIds[formId] then return M.forms[formId] end
  if nat == 201 and tonumber(unownLetter) and unownLetter > 0 then
    return 1024 + math.floor(unownLetter) - 1 -- existing Unown handling
  end
  if nat >= 906 then return M.national[nat] end
  return nat
end
return M
